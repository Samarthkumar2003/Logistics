"""Replying to an email from the dashboard, and reading back what was sent.

Like /send-rfq, every send here is an explicit operator action, signed by the
operator (sender_or_422), and routed through the one guarded send function.
"""

import logging

from fastapi import APIRouter, Request
from pydantic import BaseModel, Field

from backend.app.errors import AppException
from backend.app.routes.rfq import MAX_ATTACHMENT_TOTAL_BYTES, AttachmentInput
from backend.app.sender import sender_or_422
from backend.services import sent_reply_service
from backend.services.sent_reply_service import ReplyError

logger = logging.getLogger(__name__)
router = APIRouter(tags=["replies"])


class ReplyRequest(BaseModel):
    # The service enforces the real body limit with a readable message; this
    # bound only stops an absurd payload before it is parsed into memory.
    body: str = Field(max_length=sent_reply_service.MAX_BODY_CHARS * 2)
    cc: list[str] = Field(default_factory=list, max_length=sent_reply_service.MAX_CC * 2)
    attachments: list[AttachmentInput] = Field(default_factory=list)
    # One per composed reply, generated by the browser. See sent_reply_service.
    idempotency_key: str = Field(min_length=1, max_length=sent_reply_service.MAX_KEY_CHARS)


def _user_id(request: Request) -> str:
    claims = getattr(request.state, "claims", None)
    return (getattr(claims, "user_id", "") or "") if claims else ""


@router.get("/emails/{email_id}/sent-replies")
def list_sent_replies(email_id: str):
    """Every reply the desk sent to this email from the app, newest first."""
    try:
        return {"replies": sent_reply_service.list_for_email(email_id)}
    except Exception as e:
        logger.exception("Failed to list sent replies for %s", email_id)
        raise AppException(status_code=500, detail=f"Failed to list sent replies: {e}")


@router.post("/emails/{email_id}/reply")
def send_reply(email_id: str, payload: ReplyRequest, request: Request):
    """Send one reply to this email's sender, in the same thread.

    A provider failure is NOT an HTTP error: the attempt is recorded with status
    `failed` and returned like any other row, because the record is the point.
    HTTP errors are reserved for requests that sent nothing.
    """
    sender = sender_or_422(request)
    total_bytes = sum(len(a.data_base64) for a in payload.attachments) * 3 // 4
    if total_bytes > MAX_ATTACHMENT_TOTAL_BYTES:
        raise AppException(
            status_code=413,
            detail=f"Attachments total {total_bytes // 1024}KB, over the "
                   f"{MAX_ATTACHMENT_TOTAL_BYTES // 1024 // 1024}MB limit",
        )
    try:
        return sent_reply_service.send_reply(
            email_id=email_id,
            body=payload.body,
            sender=sender,
            idempotency_key=payload.idempotency_key,
            user_id=_user_id(request),
            cc=payload.cc,
            attachments=[a.model_dump() for a in payload.attachments],
        )
    except ReplyError as e:
        raise AppException(status_code=e.status_code, detail=e.detail)
    except Exception as e:
        logger.exception("Reply to %s failed", email_id)
        raise AppException(status_code=500, detail=f"Reply failed: {e}")


@router.post("/sent-replies/{reply_id}/retry")
def retry_sent_reply(reply_id: str, request: Request):
    """Send a failed reply again, unchanged. Refused for replies with attachments
    (their bytes are not stored) and for anything not currently failed."""
    sender_or_422(request)
    try:
        return sent_reply_service.retry(reply_id)
    except ReplyError as e:
        raise AppException(status_code=e.status_code, detail=e.detail)
    except Exception as e:
        logger.exception("Retry of reply %s failed", reply_id)
        raise AppException(status_code=500, detail=f"Retry failed: {e}")
